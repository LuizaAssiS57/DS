package Introducao;
public class Operacao {
    public static void main(String[] args) {
        int nota1 = 8;
        int nota2 = 5;

        int media = (nota1+nota2)/2;
        int mult = nota1 * nota2;
        int sub = nota1 - nota2;
        int div = nota1 / nota2;

        System.out.println(media);
        System.out.println(mult);
        System.out.println(sub);
        System.out.println(div);
    }
}
